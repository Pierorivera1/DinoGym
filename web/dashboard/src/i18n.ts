/** Range ids are the English labels: 1M, 3M, 6M, 1Y, ALL. */
function rangeWords(range: string): string {
  return { "1M": "1 month", "3M": "3 months", "6M": "6 months", "1Y": "1 year" }[range] ?? range;
}

function rangeWordsEs(range: string): string {
  return { "1M": "1 mes", "3M": "3 meses", "6M": "6 meses", "1Y": "1 año" }[range] ?? range;
}

